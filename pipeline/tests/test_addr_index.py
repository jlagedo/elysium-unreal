def at(rel: str, needle: str) -> int:
    """The 1-based line of `rel`'s fixture text that holds `needle`."""
    return next(number for number, line in enumerate(FILES[rel].split("\n"), 1) if needle in line)


@pytest.fixture
def repo(tmp_path, monkeypatch) -> Path:
    root = tmp_path / "repo"
    for rel, text in FILES.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")         # CRLF on Windows: the index must not care
    monkeypatch.setenv("ELYSIUM_WORK_ROOT", str(tmp_path / "work"))
    monkeypatch.setattr(ai, "REPO", root)
    monkeypatch.setattr(ai, "_CURRENT", None)
    yield root
    if ai._CURRENT is not None:
        ai._CURRENT.close()


def ask(*queries: str, rows: int = 8) -> str:
    return ai.where(list(queries), rows)


def docs_lines(out: str) -> int:
    return int(re.search(r"docs \(docs/vtmb, docs/contracts\): (\d+) line", out).group(1))


def test_an_address_finds_its_ledger_rows_docs_sections_port_lines_and_specs(repo):
    out = ask(f"0x{ADDR}")
    assert f"0x{ADDR}  CAI_BaseNPC::SelectSchedule" in out
    # The rows OF the address, per table -- and the verdict overlay carries it bare, without `0x`.
    assert f"functions.md:{at('docs/vtmb/npc-kernel/functions.md', ADDR)}  0x1028a380 | " \
           f"CAI_BaseNPC::SelectSchedule | 1650" in out
    assert f"slots.md:{at('docs/vtmb/npc-kernel/slots.md', ADDR)}  438 | 0x1028a380 " \
           f"CAI_BaseNPC::SelectSchedule" in out
    assert "kernel_verdicts.tsv:3  1028a380 | rule | 19-29" in out
    assert "unported.tsv:3  CAI_BaseNPC | 438 | 0x1028a380" in out
    # A heading that holds the address is listed first and marked; a mention names its section.
    heading = at(SCHEDULE, "## `0x")
    assert f"npc-ai/schedule.md:{heading}  [heading] `0x1028a380` `CAI_BaseNPC::SelectSchedule`" in out
    body = at(SCHEDULE, "The base selector")
    assert f"npc-ai/schedule.md:{body}  § `0x1028a380` `CAI_BaseNPC::SelectSchedule`" in out
    assert out.index(f"schedule.md:{heading}") < out.index(f"schedule.md:{body}")
    # The port: source before tests, the function a line sits in, a generated table set apart.
    assert "Private/Substrate/Select.cpp:1" in out
    assert "Private/Substrate/Select.cpp:6  in FElysiumNpc::SelectSchedule" in out
    assert out.index("Substrate/Select.cpp") < out.index("Tests/SelectTests.cpp")
    assert "plus 1 in 1 generated table(s), which are not citations" in out
    assert "specs (docs/specs): 1 line(s) in 1 file(s): 0002-x x1" in out


def test_every_spelling_of_an_address_is_the_same_query(repo):
    strip = lambda text: text.split("\n", 1)[1]            # the echoed query is the only difference
    assert strip(ask(f"0x{ADDR}")) == strip(ask(ADDR)) == strip(ask(f"FUN_{ADDR}"))


