def test_verdict_reads_one_address_a_band_or_the_standing(repo):
    one = ai.verdict([f"0x{ADDR}"])
    assert "0x1028a380  rule       band 19-29  CAI_BaseNPC::SelectSchedule" in one
    assert "target: FElysiumNpc::BaseSelectSchedule" in one and "the ladder" in one
    dead = ai.verdict([], which="dead")
    assert "10300000" in dead and "1028a380" not in dead
    count = ai.verdict([], count=True)
    assert "3 verdict row(s) of 3" in count and "19-29\t2\t0\t0\t0\t0\t2" in count
    assert "0-4\t0\t0\t0\t1\t0\t1" in count
    assert "no verdict row matches" in ai.verdict([f"0x{ADDR}"], band="0-4")


def test_cited_says_where_the_port_cites_an_address_and_never_counts_a_generated_table(repo):
    out = ai.cited([f"0x{ADDR}", "0x10300000", "0x1028a3f0"])
    assert ("0x1028a380  CAI_BaseNPC::SelectSchedule  cited 3x in 2 file(s): "
            "Select.cpp:1,6; SelectTests.cpp:1") in out
    assert "0x10300000  CNPC_Crow::StartTask  NOT CITED by the port" in out    # only a generated one has it
    assert "0x1028a3f0  CAI_BaseNPC::StartTask  cited 1x in 1 file(s): Select.cpp:6" in out
    assert "2 of 3 address(es) cited by the port" in out


def test_cited_over_a_table_lists_only_the_addresses_nothing_cites(repo):
    out = ai.cited([], table="unported.tsv", column="address")
    assert "0x10300000  CNPC_Crow::StartTask  NOT CITED" in out and "0x10300100" in out
    assert "CAI_BaseNPC::SelectSchedule  cited" not in out and "1 of 3 address(es) cited" in out
    rules = ai.cited([], table="unported.tsv", where_=["verdict=rule"], show_all=True)
    assert "0x10300100" not in rules and "0x1028a380  CAI_BaseNPC::SelectSchedule  cited" in rules
    assert "has no column 'nope'" in ai.cited([], table="unported.tsv", column="nope")


def test_rows_filters_projects_and_counts_a_table(repo):
    out = ai.rows_of("unported.tsv", ["verdict=rule"], columns="class,address")
    assert out.splitlines()[0] == "# docs/vtmb/npc-kernel/unported.tsv: 2 of 3 rows"
    assert out.splitlines()[1:] == ["class\taddress", "CAI_BaseNPC\t0x1028a380",
                                    "CNPC_Crow\t0x10300000"]
    grid = ai.rows_of("unported.tsv", [], count_by="class,verdict")
    assert "1\tCAI_BaseNPC\trule" in grid and "1\tCNPC_Crow\tdead" in grid
    start = ai.rows_of("kernel_verdicts.tsv", ["band=19-29", "target~Start"], columns="address")
    assert start.splitlines()[2:] == ["1028a3f0"]
    assert ai.rows_of("unported.tsv", ["slot>=440"], columns="slot").splitlines()[2:] == ["442"]
    with pytest.raises(SystemExit, match="is not a filter"):
        ai.rows_of("unported.tsv", ["nope=1"])
    with pytest.raises(SystemExit, match="no table named missing.tsv"):
        ai.rows_of("missing.tsv", [])


def test_an_ambiguous_table_name_lists_its_candidates(repo):
    (repo / "docs/vtmb/other").mkdir()
    (repo / "docs/vtmb/other/unported.tsv").write_text("a\tb\n", encoding="utf-8")
    with pytest.raises(SystemExit, match="ambiguous"):
        ai.resolve_table("unported.tsv")
    assert ai.resolve_table("npc-kernel/unported.tsv").parent.name == "npc-kernel"


def test_the_command_line_entry_prints_the_answer(repo, capsys):
    assert ai.run("where", [f"0x{ADDR}", "--limit", "2"]) == 0
    assert f"== 0x{ADDR}" in capsys.readouterr().out
    assert ai.run("rows", ["unported.tsv", "--count-by", "verdict"]) == 0
    assert "2\trule" in capsys.readouterr().out
    assert ai.run("where", ["--stats"]) == 0
    assert "files," in capsys.readouterr().out
