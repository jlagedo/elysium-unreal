def test_the_index_is_rebuilt_exactly_when_an_input_changes(repo):
    first = ai.ensure_index()
    directory = first.directory
    assert ai.ensure_index() is first                    # nothing to load, nothing to build
    pickles = sorted(directory.glob("index-*.pkl"))
    assert len(pickles) == 1
    stamp = pickles[0].stat().st_mtime_ns

    ai._CURRENT.close()
    ai._CURRENT = None
    assert ai.ensure_index().key == first.key and pickles[0].stat().st_mtime_ns == stamp   # loaded

    before = docs_lines(ask(f"0x{ADDR}"))
    path = repo / SCHEDULE
    path.write_text(FILES[SCHEDULE] + f"\nA late mention of 0x{ADDR}.\n", encoding="utf-8")
    assert ai.ensure_index().key != first.key
    assert docs_lines(ask(f"0x{ADDR}")) == before + 1
    assert len(list(directory.glob("index-*.pkl"))) == 1                # the old build was removed


def test_a_deleted_file_leaves_the_rebuilt_answer_without_it(repo):
    ask(f"0x{ADDR}")
    (repo / "Source/ElysiumUE/Private/Substrate/Select.cpp").unlink()
    assert "Select.cpp" not in ask(f"0x{ADDR}")


def test_section_prints_the_section_a_heading_names_not_the_file(repo):
    out = ai.section("CAI_BaseNPC::SelectSchedule")
    assert "2 section(s) whose heading names it" in out
    deep, parent = at(SCHEDULE, "### The dead arm"), at(SCHEDULE, "## `0x")
    assert out.index(f"schedule.md:{deep}") < out.index(f"schedule.md:{parent}")  # the deeper first
    assert "### The dead arm of CAI_BaseNPC::SelectSchedule" in out and "chosen here." in out
    assert "Prose before any address." not in out and "Another section" not in out
    whole = ai.section("CAI_BaseNPC::SelectSchedule", pick=2)
    assert "switches on the state" in whole and "The dead arm" in whole
    paged = ai.section("CAI_BaseNPC::SelectSchedule", lines=2, pick=2)
    assert f"--from {parent + 2}" in paged and "switches on the state" not in paged
    assert "no docs section mentions" in ai.section("0x10300100")


