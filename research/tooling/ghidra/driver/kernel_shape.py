#!/usr/bin/env python3
"""The NPC kernel's shape: every member with a type, every slot with a signature.

Story 29b-0 of `docs/specs/0002-npc-ai/spec.md`. The ledger (`kernel_ledger.py`) says which
offsets exist and who touches them; a C++ declaration also needs what each offset *is* and what
each virtual takes and returns. This tool derives both from what the image states, merges the
rows recovered by reading bodies (the two overlays beside it), and writes

* `layout.md` / `layout.tsv` — the flattened `CAI_BaseNPCTroika` layout from offset 0 to its
  extent, then every species class's own words: one row per datamap member (type, count, flags,
  key — `datamap_layout.py`), per touched offset inside a member the datamaps do not describe
  inside (`COutputEvent`, `CUtlVector`, `Vector`, array elements), and per touched offset no
  datamap declares, with the access evidence the decompiled bodies carry and the overlay's
  recovered name and type.
* `signatures.md` / `signatures.tsv` — one row per primary-vtable slot: the declaration, its
  tier, the image's arity (`RET n`), the SDK's, how call sites use the return value, and what the
  decompiler's prototypes say about the parameters.

**Receivers.** A body's `this` is an NPC only when the body fills a family class's vtable, is a
method Ghidra typed on a family class, or fills a slot of one of the entity classes an NPC
derives from. A touch is filed under the most-base class in its receiver's chain whose extent
contains the offset, so a base-class body can never place a word past its own class. Global
bodies in the kernel's closure are counted as guessed receivers (`?`).

**Tiers** (`layout`): `datamap` (a record states it), `interior` (SDK 2013 sub-layout of a record
the datamaps do not describe inside), `walked` / `sdk-order` / `doc` (the overlay, with its
evidence), `evidence` (no name; the type the accesses agree on), `open` (the accesses disagree
or say nothing). **Tiers** (`signatures`): `sdk` (SDK 2013 declares the slot's method and the
image pops the words it declares), `walked` (the overlay), `evidence` (the arity is the image's,
the types are the call sites' and the prototypes' majority), `open`.

Usage::

    uv run elysium research kernel_shape
    uv run elysium research kernel_shape --check
    uv run elysium research kernel_shape --residue <path>   # the rows a reading has not settled
"""

