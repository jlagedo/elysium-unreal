TROIKA = "CAI_BaseNPCTroika"
NPC_START = 0x19B0          # first word past `CBaseCombatCharacter`'s layout
FIELDS_OVERLAY = _HERE / "kernel_fields.tsv"
SIGNATURES_OVERLAY = _HERE / "kernel_signatures.tsv"
