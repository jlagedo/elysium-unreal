def _cell(text: str) -> str:
    return (text or "").replace("|", "¦").replace("\n", " ")


def _head(ledger: kl.Ledger, title: str, blurb: str) -> list[str]:
    head = ledger._head(title, blurb)
    head[0] = BANNER
    head[3] = head[3].replace("kernel_ledger", "kernel_shape")
    return head


