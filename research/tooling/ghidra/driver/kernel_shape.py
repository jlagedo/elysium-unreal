HEX = r"0x[0-9a-fA-F]+|\d+"
# `(int)this + [i * s +] 0xOFF [+ i [* s]]`: the member access Ghidra writes for an untyped word.
CORE_RE = re.compile(
    rf"\(int\)this\s*\+\s*(?:(?P<ia>[A-Za-z_]\w*)\s*\*\s*(?P<sa>{HEX})\s*\+\s*)?(?P<off>0x[0-9a-fA-F]+)"
    rf"(?:\s*\+\s*(?P<ib>[A-Za-z_]\w*)(?:\s*\*\s*(?P<sb>{HEX}))?)?")
FIELD_ADDR_RE = re.compile(r"&this->field_0x(?P<off>[0-9a-fA-F]+)")
FIELD_BARE_RE = re.compile(r"(?<![&\w>.])this->field_0x(?P<off>[0-9a-fA-F]+)")
# A constructor or destructor installing a secondary base's table: `… + 0x19b0) = &vftable_X_at6576`.
VFTABLE_WRITE_RE = re.compile(
    r"(?:\(int\)this\s*\+\s*(?P<a>0x[0-9a-fA-F]+)\)|&this->field_0x(?P<b>[0-9a-fA-F]+))\s*=\s*&?(?:PTR_)?vftable")
CTOR_RE = re.compile(r"(?<![\w.>])\*(this|param_1|in_ECX)\s*=\s*&vftable_([A-Za-z_]\w*?)\s*;")
HINT_PATH_RE = re.compile(r"npc|schedule|stealth|combat|grapple|feed|dialog|senses|social|squad|"
                          r"lifecycle|conditions|programs|authored-control|population", re.I)
DEREF_BEFORE_RE = re.compile(r"(?P<outer>\*?)\*\s*\((?P<t>[A-Za-z_][\w ]*?)\s*(?P<p>\*+)\)\s*\(?\s*$")
POINTER_TAIL_RE = re.compile(r"^\s*\)?\s*\+\s*(?:0x[0-9a-fA-F]+|\d+)")
FUN_RE = re.compile(r"^(?:thunk_)?FUN_([0-9a-fA-F]{8})$")
CALL_SITE_RE = re.compile(r"^\s*[0-9a-fA-F]{8}\s+CALL\s+dword ptr \[\w+ \+ 0x([0-9a-fA-F]+)\]\s*$")
ASM_LINE_RE = re.compile(r"^\s*[0-9a-fA-F]{8}\s+(?P<mn>[A-Z]+)\s*(?P<ops>.*)$")
PROTO_RE = re.compile(
    r"^(?P<ret>[\w \*]*?)\s*(?:__thiscall|__fastcall|__stdcall|__cdecl)?\s*"
    r"(?:[\w:~<>]+)\s*\((?P<params>[^()]*)\)\s*$")
X87_USE = {"FSTP", "FST", "FCOMP", "FCOM", "FCOMPP", "FUCOMP", "FUCOM", "FUCOMPP", "FMUL", "FADD",
           "FSUB", "FSUBR", "FDIV", "FDIVR", "FISTP", "FXCH", "FCHS", "FABS", "FTST"}

INT_TYPES = {"undefined4": 4, "int": 4, "uint": 4, "long": 4, "ulong": 4, "dword": 4, "int32": 4,
             "uint32": 4, "undefined2": 2, "short": 2, "ushort": 2, "word": 2, "wchar_t": 2,
             "wchar16": 2, "undefined1": 1, "byte": 1, "char": 1, "bool": 1, "uchar": 1,
             "undefined": 1, "uint8": 1, "int8": 1, "undefined8": 8, "longlong": 8,
             "ulonglong": 8, "qword": 8}


@dataclass
class Evidence:
    """What the bodies do with one offset of one layout."""
    kinds: collections.Counter = field(default_factory=collections.Counter)
    structs: collections.Counter = field(default_factory=collections.Counter)
    callees: collections.Counter = field(default_factory=collections.Counter)
    strides: collections.Counter = field(default_factory=collections.Counter)
    writers: set = field(default_factory=set)
    readers: set = field(default_factory=set)
    receivers: set = field(default_factory=set)
    guessed: set = field(default_factory=set)

    def summary(self, limit: int = 4) -> str:
        parts = [f"{k}×{n}" for k, n in sorted(self.kinds.items(), key=lambda kv: (-kv[1], kv[0]))]
        parts += [f"struct {s}×{n}" for s, n in sorted(self.structs.items())]
        parts += [f"stride {s}" for s in sorted(self.strides)]
        parts += [f"&→{c}×{n}" for c, n in sorted(self.callees.items(), key=lambda kv: (-kv[1], kv[0]))[:limit]]
        return ", ".join(parts)

    def inferred_type(self) -> str:
        """The one type every access agrees on, or ''."""
        kinds = set(self.kinds)
        kinds.discard("addr")
        if "vftable" in kinds:
            return "vftable*"
        if not kinds:
            return ""
        if kinds == {"float"}:
            return "float"
        if kinds <= {"ptr", "objptr", "w4"} and kinds & {"ptr", "objptr"}:
            return "pointer"
        if kinds == {"double"}:
            return "double"
        widths = {k for k in kinds if k.startswith("w")}
        if kinds == widths and len(widths) == 1:
            return {"w1": "int8", "w2": "int16", "w4": "int32", "w8": "int64"}[next(iter(widths))]
        return ""


@dataclass
class Row:
    table: str
    off: int
    size: int | None
    member: str
    type: str
    field_type: str
    count: int
    flags: str
    layer: str
    tier: str
    evidence: Evidence | None
    hints: str = ""
    note: str = ""


def _parse_type(t: str, p: int) -> tuple[str, str | None]:
    """A Ghidra cast `*(T p*)` read as the member's kind: `w1`…`w8`, `float`, `double`, `ptr`, or a
    struct name."""
    t = re.sub(r"\bunsigned\s+", "u", t.strip())
    if p >= 2:
        return "ptr", None
    if t == "float":
        return "float", None
    if t in ("double", "float10"):
        return "double", None
    if t in INT_TYPES:
        return f"w{INT_TYPES[t]}", None
    if t in ("code", "void", "pointer"):
        return "ptr" if t != "void" else "addr", None
    return "struct", t


def enclosing_call(code: str, pos: int) -> str | None:
    """The function an expression at `pos` is an argument of (or `None`)."""
    depth = 0
    i = pos - 1
    while i >= 0 and code[i] not in ";{}":
        c = code[i]
        if c == ")":
            depth += 1
        elif c == "(":
            if depth == 0:
                m = re.search(r"([A-Za-z_]\w*(?:::~?\w+)*)\s*$", code[:i])
                if m and m.group(1) not in ("if", "while", "for", "switch", "return", "sizeof"):
                    return m.group(1)
            else:
                depth -= 1
        i -= 1
    return None


def scan_body(code: str, token: str = "this",
              elem: int = 4) -> list[tuple[int, str, str | None, bool, str | None, int | None]]:
    """Every untyped member access through the receiver `token` in a decompiled body:
    (offset, kind, struct type, is-write, consuming call, stride). `elem` is the width of the
    receiver's pointee when Ghidra typed it as an array (`param_1[0x66c]` is word 0x66c)."""
    out = []
    spans = []
    core = CORE_RE if token == "this" else re.compile(CORE_RE.pattern.replace("this", re.escape(token)))
    for m in core.finditer(code):
        spans.append((m.start(), m.end(), int(m.group("off"), 16),
                      m.group("sa") or m.group("sb"), bool(m.group("ib") and not m.group("sb"))))
    if token != "this":
        for m in re.finditer(rf"(?<![\w.>]){re.escape(token)}\[(0x[0-9a-fA-F]+|\d+)\]", code):
            tail = code[m.end():m.end() + 24]
            head = code[max(0, m.start() - 30):m.start()]
            off = int(m.group(1), 0) * elem
            if re.search(r"=\s*&?(?:PTR_)?vftable", tail[:20]):
                out.append((off, "vftable", None, True, None, None))
            else:
                kind = "ptr" if re.search(r"\*\s*\([\w ]+\*\)\s*$", head) or POINTER_TAIL_RE.match(tail) \
                    else f"w{elem}"
                out.append((off, kind, None, bool(kl.ASSIGN_TAIL_RE.match(tail)), None, None))
        if re.search(rf"(?<![\w.>])\*{re.escape(token)}\s*=\s*&?(?:PTR_)?vftable", code):
            out.append((0, "vftable", None, True, None, None))
    for m in (FIELD_ADDR_RE.finditer(code) if token == "this" else ()):
        spans.append((m.start(), m.end(), int(m.group("off"), 16), None, False))
    for start, end, off, stride_text, _ in spans:
        head = code[max(0, start - 60):start]
        # `*(T *)((int)this + off)`: the core sits one paren inside the deref's own.
        deref = DEREF_BEFORE_RE.search(head)
        stride = int(stride_text, 0) if stride_text else None
        if deref:
            close = end
            if code[start - 1:start] == "(" and code[end:end + 1] == ")":
                close = end + 1
            kind, struct = _parse_type(deref.group("t"), len(deref.group("p")))
            if kind == "ptr" and deref.group("outer"):
                kind = "objptr"
            tail = code[close:close + 24]
            if kind.startswith("w") and kind in ("w4",) and POINTER_TAIL_RE.match(tail):
                kind = "ptr"
            write = bool(kl.ASSIGN_TAIL_RE.match(tail))
            out.append((off, kind, struct, write, None, stride))
        else:
            out.append((off, "addr", None, False, enclosing_call(code, start), stride))
    if token != "this":
        return out
    for m in VFTABLE_WRITE_RE.finditer(code):
        out.append((int(m.group("a") or m.group("b"), 16), "vftable", None, True, None, None))
    for m in FIELD_BARE_RE.finditer(code):
        tail = code[m.end():m.end() + 12]
        out.append((int(m.group("off"), 16), "w1", None, bool(kl.ASSIGN_TAIL_RE.match(tail)), None, None))
    return out


def sdk_members(sdk: sdk_layout.Sdk | None, cls: str) -> list[tuple[str, str]]:
    """(type, name) of the data members `cls` declares in the SDK header, in declaration order."""
    if sdk is None or sdk.header(cls) is None:
        return []
    text = sdk.header(cls).read_text(encoding="utf-8", errors="replace")
    kept, _ = sdk_layout.preprocess(text)
    joined = "\n".join(line for _, line in kept)
    head = re.search(rf"\b(?:class|struct|abstract_class)\s+{re.escape(cls)}\s*(:[^;{{]*)?\{{", joined)
    if not head:
        return []
    open_at = head.end() - 1
    body = joined[open_at + 1:sdk_layout._match_brace(joined, open_at)]
    out: list[tuple[str, str]] = []
    depth = 0
    statement: list[str] = []
    for c in body:
        if c == "{":
            depth += 1
            if depth == 1:
                statement = []
            continue
        if c == "}":
            depth -= 1
            statement = []
            continue
        if depth:
            continue
        if c == ";":
            stmt = re.sub(r"\b(public|protected|private)\s*:", " ", "".join(statement)).strip()
            stmt = re.sub(r"^(?:[A-Z_][A-Z0-9_]*\s*\([^;]*?\)\s*)+", "", stmt).strip()
            statement = []
            if not stmt or "(" in stmt or stmt.startswith(("typedef", "friend", "using", "enum",
                                                           "static", "class", "struct", "template")):
                continue
            m = re.match(r"^(?P<type>.+?)\s*[\s\*&](?P<name>[A-Za-z_]\w*)\s*(?:\[[^\]]*\])?\s*(?::\s*\d+)?$",
                         stmt, re.S)
            if m:
                out.append((" ".join(m.group("type").split()), m.group("name")))
            continue
        statement.append(c)
    return out


class Shape:
    def __init__(self, ledger: kl.Ledger, records: dl.Records, sdk: sdk_layout.Sdk | None):
        self.ledger = ledger
        self.records = records
        self.sdk = sdk
        self.module = ledger.module
        self.words = name_passes.Corpus(ledger.db, self.module, ledger.listing)
        self.base_of: dict[str, str] = {}
        for cls, entry in records.by_class.items():
            if entry.get("base"):
                self.base_of[cls] = entry["base"]
        self.base_of.update({c: b for c, b in ledger.bases.items() if b})
        self.family = set(ledger.family)
        self.troika_chain = set(self._chain(TROIKA))
        self._extent: dict[str, int] = {}
        self._layout: dict[str, list[dl.Member]] = {}
        self.evidence: dict[str, dict[int, Evidence]] = collections.defaultdict(
            lambda: collections.defaultdict(Evidence))
        self.misplaced = collections.Counter()
        self.guess_only: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
        self.fields_overlay: dict[tuple[str, int], list[dict]] = collections.defaultdict(list)
        self.signatures_overlay: dict[tuple[int, str], dict] = {}

    # -- classes -------------------------------------------------------------------------------

    def _chain(self, cls: str) -> list[str]:
        """`cls` and its bases, most-derived first."""
        out = []
        while cls and cls not in out:
            out.append(cls)
            cls = self.base_of.get(cls, "")
        return out

    def layout(self, cls: str) -> list[dl.Member]:
        if cls not in self._layout:
            owner = next((c for c in self._chain(cls) if c in self.records.by_class), None)
            members = dl.flatten(self.records, owner) if owner else []
            # Records the image's static tables state that the builder replay does not hold.
            taken = {m.off for m in members}
            for row in self.ledger.db.execute(
                    "SELECT off, name, len, note FROM fields WHERE module = ? AND cls = ? ORDER BY off",
                    (self.module, cls)):
                code = dl.FIELD_TYPE_CODE_RE.search(row["note"] or "")
                name = dl.type_from_code(int(code.group(1))) if code else ""
                if row["off"] in taken or name in ("", "void", "embedded", "custom"):
                    continue
                layer = next((c for c in reversed(self._chain(cls))
                              if c in self.records.by_class and self._span(c) > row["off"]), cls)
                member = dl.Member(row["off"], row["name"], layer, name, 1, ("SAVE",), None, None, None,
                                   dl.FIELD_TYPES[name][2], "image record (not in the builder replay)")
                member.source_type = dl.FIELD_TYPES[name][1]
                member.interior = dl._interior(member)
                members.append(member)
                taken.add(row["off"])
            members.sort(key=lambda m: (m.off, m.parent != "", m.name))
            self._layout[cls] = members
        return self._layout[cls]

    def _span(self, cls: str) -> int:
        tops = [m for m in dl.flatten(self.records, cls, expand=False)]
        return max((m.off + (m.width or 4) for m in tops), default=0)

    def extent(self, cls: str) -> int:
        if cls not in self._extent:
            members = [m for m in self.layout(cls) if not m.parent]
            self._extent[cls] = max((m.off + (m.width or 4) for m in members), default=0)
        return self._extent[cls]

    def table_for(self, owner: str, off: int) -> str:
        """The class a touch through `owner` at `off` belongs to: the most-base class of the chain
        whose extent contains it (the Troika layout for its whole chain)."""
        for cls in reversed(self._chain(owner)):
            if off < self.extent(cls):
                return TROIKA if cls in self.troika_chain else cls
        return TROIKA if owner in self.troika_chain else owner

    def receiver(self, fn: kl.Function) -> tuple[str | None, bool]:
        """The class a body's `this` is laid out as, and whether that is a guess."""
        if fn.ns in self.family:
            return fn.ns, False
        holders = {c for c, _ in fn.slots}
        npc_holders = {c for c in holders if c in self.family or c in self.troika_chain}
        if npc_holders:
            return min(npc_holders, key=lambda c: (len(self._chain(c)), c)), False
        if fn.ns in self.troika_chain:
            return fn.ns, False
        if fn.addr in self.ledger.closure and fn.ns in ("", "Global") \
                and fn.cc in ("__thiscall", "__fastcall"):
            return TROIKA, True
        return None, False

    def constructed(self, fn: kl.Function) -> tuple[str, str, int] | None:
        """A constructor or destructor: the body installs a family class's primary vtable on its
        receiver (`*param_1 = &vftable_CAI_BaseNPCTroika`). Returns the most-derived class it
        installs, the receiver's token, and the receiver's pointee width."""
        found = [(m.group(1), m.group(2)) for m in CTOR_RE.finditer(fn.code)
                 if m.group(2) in self.family or m.group(2) in self.troika_chain]
        if not found:
            return None
        token, cls = max(found, key=lambda tc: len(self._chain(tc[1])))
        head = next((line for line in fn.code.splitlines() if token in line and "(" in line), "")
        pointee = re.search(rf"(\w+)\s*\*\s*{re.escape(token)}(?!\w)", head)
        elem = INT_TYPES.get(pointee.group(1), 4) if pointee else 4
        return cls, token, elem

    # -- evidence ------------------------------------------------------------------------------

    def gather(self) -> None:
        bodies = []
        for fn in self.ledger.functions.values():
            if fn.thunk or not fn.code:
                continue
            owner, guessed = self.receiver(fn)
            token, elem = "this", 4
            ctor = self.constructed(fn)
            if ctor is not None and (owner is None or guessed):
                (owner, token, elem), guessed = ctor, False
            if owner is not None:
                bodies.append((guessed, fn.addr, fn, owner, token, elem))
        for guessed, _, fn, owner, token, elem in sorted(bodies, key=lambda b: (b[0], b[1])):
            for off, kind, struct, write, callee, stride in scan_body(fn.code, token, elem):
                if off >= 0x10000:
                    continue
                if owner not in self.family and off >= self.extent(owner):
                    self.misplaced[owner] += 1   # an entity-class body cannot reach past its class
                    continue
                table = self.table_for(owner, off)
                if guessed and off not in self.evidence[table]:
                    self.guess_only[table][off] += 1   # a guessed receiver alone does not make a word
                    continue
                ev = self.evidence[table][off]
                if kind == "struct":
                    ev.structs[struct] += 1
                else:
                    ev.kinds[kind] += 1
                if callee:
                    fun = FUN_RE.match(callee)
                    if fun and fun.group(1).lower() in self.ledger.functions:
                        callee = self.ledger.functions[fun.group(1).lower()].label
                    ev.callees[callee] += 1
                if stride:
                    ev.strides[stride] += 1
                (ev.writers if write else ev.readers).add(fn.addr)
                ev.receivers.add(owner)
                if guessed:
                    ev.guessed.add(fn.addr)

    def load_overlays(self) -> None:
        if FIELDS_OVERLAY.is_file():
            for line in FIELDS_OVERLAY.read_text(encoding="utf-8").splitlines():
                if not line.strip() or line.startswith("#"):
                    continue
                parts = line.split("\t")
                if len(parts) < 8 or parts[0] != self.module:
                    continue
                module, cls, off, name, typ, count, tier, evidence = parts[:8]
                self.fields_overlay[(cls, int(off, 16))].append({
                    "name": name, "type": typ, "count": int(count or 1), "tier": tier,
                    "evidence": evidence})
        if SIGNATURES_OVERLAY.is_file():
            for line in SIGNATURES_OVERLAY.read_text(encoding="utf-8").splitlines():
                if not line.strip() or line.startswith("#"):
                    continue
                parts = line.split("\t")
                if len(parts) < 8 or parts[0] != self.module:
                    continue
                module, slot, method, ret, params, const, tier, evidence = parts[:8]
                cls = parts[8].strip() if len(parts) > 8 else ""
                cls = "" if cls in self.troika_chain else cls
                self.signatures_overlay[(int(slot), cls)] = {"cls": cls,
                    "method": method, "ret": ret, "params": params, "const": const == "const",
                    "tier": tier, "evidence": evidence}

    # -- name hints ----------------------------------------------------------------------------

    def hints(self, off: int) -> str:
        found: dict[str, str] = {}
        if off < NPC_START:
            return ""
        cites = list(self.ledger.oracle_off.get(off, [])) + list(self.ledger.port_off.get(off, []))
        spelled = re.compile(rf"\+0x0*{off:x}\b", re.I)
        for c in sorted(cites, key=lambda c: (c.path, c.line)):
            if not HINT_PATH_RE.search(c.path):
                continue
            for m in spelled.finditer(c.text):
                window = c.text[max(0, m.start() - 50):m.end() + 50]
                names = re.findall(r"\b(m_[A-Za-z]\w*|bf?[A-Z]\w*)\b", window)
                for name in names:
                    found.setdefault(name, f"{c.path}:{c.line}")
        if off in self.ledger.port_member:
            found.setdefault(f"port:{self.ledger.port_member[off]}", "")
        return ", ".join(f"`{n}`" + (f" ({w})" if w else "") for n, w in list(found.items())[:3])

    def sdk_between(self, layer: str, before: str, after: str) -> str:
        members = sdk_members(self.sdk, layer)
        names = [n for _, n in members]
        if before not in names or after not in names:
            return ""
        i, j = names.index(before), names.index(after)
        if j - i <= 1 or j - i > 40:
            return ""
        declared = {m.name for m in self.layout(TROIKA)}
        run = [f"{t} {n}" for t, n in members[i + 1:j] if n not in declared]
        return "SDK 2013 between: " + "; ".join(run[:8]) + (" …" if len(run) > 8 else "") if run else ""

    # -- layout rows ---------------------------------------------------------------------------

    def rows(self) -> list[Row]:
        tables = [TROIKA] + sorted(t for t in self.evidence if t != TROIKA) \
            + sorted(c for c in self.family if c not in self.evidence and c != TROIKA
                     and c not in self.troika_chain and self._own_members(c)) \
            + sorted({c for c, _ in self.fields_overlay if c not in self.evidence and c != TROIKA})
        out: list[Row] = []
        seen_tables = []
        for table in tables:
            if table in seen_tables:
                continue
            seen_tables.append(table)
            out.extend(self._table_rows(table))
        return out

    def _own_region(self, table: str) -> int:
        if table == TROIKA:
            return 0
        parent = self.base_of.get(table, "")
        return self.extent(parent) if parent else 0

    def _own_members(self, table: str) -> list[dl.Member]:
        start = self._own_region(table)
        return [m for m in self.layout(table) if m.off >= start and (table == TROIKA or m.owner == table)]

    def overlays(self, table: str, off: int) -> list[dict]:
        """The reading overlay's rows for a word: the table's own, else an ancestor's (a member a
        base class declares, recovered once for every species that inherits it). The aggregate
        comes first, then its elements."""
        for cls in self._chain(table):
            rows = self.fields_overlay.get((cls, off))
            if rows:
                return sorted(rows, key=lambda o: (("." in o["name"] or "[" in o["name"]), o["name"]))
            if cls in self.troika_chain:
                break
        return []

    def _overlay_rows(self, table: str, off: int, layer: str, ev: Evidence | None, hints: str = "") -> list[Row]:
        out = []
        for i, o in enumerate(self.overlays(table, off)):
            out.append(Row(table, off, None, o["name"], o["type"], "", o["count"], "", layer, o["tier"],
                           ev if i == 0 else None, hints=hints if i == 0 else "", note=o["evidence"]))
        return out

    def _table_rows(self, table: str) -> list[Row]:
        members = self._own_members(table)
        by_off: dict[int, list[dl.Member]] = collections.defaultdict(list)
        for m in members:
            by_off[m.off].append(m)
        evidence = self.evidence.get(table, {})
        all_members = self.layout(table)
        tops = sorted((m for m in all_members if not m.parent), key=lambda m: m.off)
        rows: list[Row] = []
        for m in members:
            ev = evidence.get(m.off)
            source_type, note = m.source_type, ("" if m.width_source == "fieldType width" else m.width_source)
            if not m.parent and source_type == "custom":
                # the records say only "custom"; a reading names the type
                typed = next((o for o in self.overlays(table, m.off) if o["name"] == m.name), None)
                if typed:
                    source_type, note = typed["type"], f"{typed['tier']}: {typed['evidence']}"
            rows.append(Row(table, m.off, m.width, m.name, source_type,
                            dl.FIELD_TYPES.get(m.field_type, (m.field_type,))[0], m.count,
                            " ".join(f for f in m.flags if f != "SAVE") + (f" key={m.key}" if m.key else ""),
                            m.owner, "datamap", ev, note=note))
        start = self._own_region(table)
        for off in sorted(evidence):
            if off in by_off or off < start:
                continue
            ev = evidence[off]
            covers = dl.covering(all_members, off)
            overlay = self.overlays(table, off)
            if covers:
                inner = covers[-1]
                named = dl.interior_name(inner, off)
                if overlay:
                    rows.extend(self._overlay_rows(table, off, inner.owner, ev))
                elif named:
                    rows.append(Row(table, off, None, named[0], named[1], "", 1, "", inner.owner,
                                    "interior", ev, note=named[2]))
                else:
                    rows.append(Row(table, off, None, f"{inner.name}+0x{off - inner.off:x}",
                                    ev.inferred_type(), "", 1, "", inner.owner,
                                    "evidence" if ev.inferred_type() else "open", ev,
                                    note=f"inside `{inner.source_type}` ({inner.width_source})"))
                continue
            before = [m for m in tops if m.off < off]
            after = [m for m in tops if m.off > off]
            prev = before[-1] if before else None
            nxt = after[0] if after else None
            layer = prev.owner if prev else table
            context = (f"after `{prev.name}`" if prev else "") + (f", before `{nxt.name}`" if nxt else "")
            sdk_hint = self.sdk_between(layer, prev.name, nxt.name) if prev and nxt and prev.owner == nxt.owner else ""
            if overlay:
                rows.extend(self._overlay_rows(table, off, layer, ev, self.hints(off)))
                continue
            inferred = ev.inferred_type()
            rows.append(Row(table, off, None, "—", inferred, "", 1, "", layer,
                            "evidence" if inferred else "open", ev, hints=self.hints(off),
                            note="; ".join(x for x in (context.strip(", "), sdk_hint) if x)))
        # overlay rows for words no body touches through `this` (found by reading a body)
        for cls, off in sorted(self.fields_overlay):
            if cls != table or off in evidence or off in by_off or off < start:
                continue
            covers = dl.covering(all_members, off)
            layer = covers[-1].owner if covers else next(
                (m.owner for m in reversed(tops) if m.off < off), table)
            rows.extend(self._overlay_rows(table, off, layer, None))
        rows.sort(key=lambda r: (r.off, r.tier != "datamap", r.member))
        return rows

    # -- signatures ----------------------------------------------------------------------------

    def signatures(self) -> list[dict]:
        sdk_slots: list[sdk_layout.Slot] = []
        if self.sdk is not None:
            sdk_slots, _ = self.sdk.vtable(sdk_layout.NPC_CHAIN)
        by_name: dict[str, list[sdk_layout.Slot]] = collections.defaultdict(list)
        for s in sdk_slots:
            by_name[s.name].append(s)
        declared: dict[str, list[sdk_layout.Method]] = collections.defaultdict(list)
        if self.sdk is not None:
            for cls in sdk_layout.NPC_CHAIN:
                for m in self.sdk.methods(cls)[1]:
                    declared[m.name].append(m)
        usage = self._call_site_usage()
        out = []
        for slot, cls, bodies in self._slot_groups():
            fns = [self.ledger.functions[b] for b in bodies if b in self.ledger.functions]
            names = collections.Counter(f.name for f in fns if not f.unnamed and not f.name.startswith("~"))
            method = names.most_common(1)[0][0] if len(names) == 1 else ""
            if not method and names:
                method = " / ".join(sorted(names))
            words = {self.words.words(b) for b in bodies} - {None}
            protos = [p for p in (self._prototype(f) for f in fns) if p]
            ret_seen = collections.Counter(p[0] for p in protos)
            use = usage.get(slot, collections.Counter()) if not cls else collections.Counter()
            row = {"slot": slot, "cls": cls, "method": method or "", "bodies": len(bodies),
                   "words": sorted(words), "sdk_words": None, "ret": "", "params": "", "const": False,
                   "tier": "open", "why": "", "use": use, "ret_seen": ret_seen,
                   "params_seen": self._params_seen(protos)}
            if method and " / " not in method and not cls:
                self._match_sdk(row, method, words, by_name, declared)
            if row["tier"] != "sdk":
                self._from_evidence(row)
            # A reading may name the true introducer, a base with no dumped table of its own
            # (`CAI_BaseActor` under `CAI_BaseHumanoid`).
            overlay = next((self.signatures_overlay[(slot, c)] for c in ([cls] + self._chain(cls)[1:] if cls else [""])
                            if (slot, c) in self.signatures_overlay), None)
            if overlay and cls and overlay.get("cls") and overlay["cls"] != cls:
                row["cls"] = overlay["cls"]
            if overlay:
                row.update(method=overlay["method"] or row["method"], ret=overlay["ret"],
                           params=overlay["params"], const=overlay["const"], tier=overlay["tier"],
                           why=overlay["evidence"])
            out.append(row)
        return out

    def introducer(self, cls: str, slot: int) -> str:
        """The most-base class in `cls`'s chain whose own primary vtable already holds `slot`."""
        for ancestor in reversed(self._chain(cls)):
            if self.ledger.slot_count.get(ancestor, 0) > slot:
                return ancestor
        return cls

    def branch(self, cls: str, slot: int) -> str:
        """'' for a virtual of the Troika line, else the class that introduces it."""
        intro = self.introducer(cls, slot)
        return "" if intro in self.troika_chain else intro

    def _slot_groups(self) -> list[tuple[int, str, list[str]]]:
        """(slot, introducing class, bodies) per virtual. A slot is one virtual for every class
        whose chain introduces it in the Troika line (class ''); past a base's table each branch
        declares its own virtuals at the same index (`CAI_BaseHumanoid` from 583, the boss, vampire
        boss and maker branches from 617), and each is a row of its own."""
        out = []
        for slot in sorted(self.ledger.slot_bodies):
            groups: dict[str, set[str]] = collections.defaultdict(set)
            for cls, body in self.ledger.slot_bodies[slot].items():
                groups[self.branch(cls, slot)].add(body)
            for key in sorted(groups):
                out.append((slot, key, sorted(groups[key])))
        return out

    def _match_sdk(self, row: dict, method: str, words: set[int],
                   by_name: dict[str, list[sdk_layout.Slot]],
                   declared: dict[str, list[sdk_layout.Method]]) -> None:
        """The SDK 2013 declaration of `method` down the NPC chain whose stack words the image pops.
        A virtual in the SDK's table wins over a non-virtual of the same name (2003 declared some
        virtuals 2013 no longer does); an overload is picked by its word count alone."""
        virtual_keys = {s.key for s in by_name.get(method, [])}
        candidates: dict[tuple, tuple[sdk_layout.Method, int | None, str]] = {}
        for m in declared.get(method, []):
            if m.name == "~":
                continue
            sw = self.sdk.stack_words(m.params, m.ret)
            candidates.setdefault((m.params, m.ret, m.const), (m, sw, "virtual" if m.key in virtual_keys else "non-virtual"))
        if not candidates:
            return
        retail = next(iter(words)) if len(words) == 1 else None
        fits = []
        for key, (m, sw, kind) in candidates.items():
            if retail is None or sw is None:
                continue
            if sw == retail:
                fits.append((m, sw, kind, ""))
            elif m.ret == "string_t" and sw + 1 == retail:
                fits.append((m, sw, kind, "; `string_t` returned through a hidden slot, as 2003's class did"))
        if len(fits) > 1:
            # one declaration repeated (a redeclaration down the chain, an `#ifdef` pair)
            if len({(f[0].params, f[0].const) for f in fits}) == 1:
                fits = [max(fits, key=lambda f: (f[2] == "virtual", bool(f[0].ret)))]
        if len(fits) > 1:
            virtual = [f for f in fits if f[2] == "virtual"]
            fits = virtual if len(virtual) == 1 else fits
        if len(fits) == 1:
            m, sw, kind, extra = fits[0]
            row.update(sdk_words=sw, ret=m.ret or "void", params=m.params.replace(",", ", "), const=m.const,
                       tier="sdk", why=f"SDK 2013 {m.cls}::{m.name} ({kind} there){extra}")
            return
        shown = "; ".join(f"{m.cls}::{m.name}({m.params}) pops {sw}" for m, sw, _ in candidates.values())
        row["sdk_words"] = next((sw for _, sw, _ in candidates.values()), None)
        if retail is None:
            row["why"] = f"SDK 2013 declares {shown}; the image's arity is unread"
        elif fits:
            row["why"] = f"SDK 2013 overloads fit {retail} word(s): {shown}"
        else:
            row["why"] = f"SDK 2013 declares {shown}; the image pops {retail}"

    def _from_evidence(self, row: dict) -> None:
        words = row["words"]
        if len(words) != 1:
            row["why"] = (row["why"] + "; " if row["why"] else "") + (
                "the bodies pop different word counts " + str(words) if words else "no body's `RET n` is read")
            return
        n = words[0]
        ret = self._return_from(row["use"], row["ret_seen"])
        params = self._params_from(row["params_seen"], n)
        if ret is None or params is None:
            row["why"] = (row["why"] + "; " if row["why"] else "") + (
                "return use disagrees" if ret is None else f"prototypes do not settle {n} word(s)")
            return
        row.update(ret=ret, params=", ".join(params), tier="evidence",
                   why=(row["why"] + "; " if row["why"] else "") + f"image pops {n} word(s)")

    @staticmethod
    def _return_from(use: collections.Counter, seen: collections.Counter) -> str | None:
        sites = sum(use.values())
        if sites:
            kind, n = use.most_common(1)[0]
            if kind == "unused" and len(use) > 1:
                kinds = {k: v for k, v in use.items() if k != "unused"}
                kind, n = max(kinds.items(), key=lambda kv: (kv[1], kv[0]))
                return {"bool": "bool", "int": "int", "ptr": "void*", "float": "float"}[kind]
            if n * 3 >= sites * 2:
                return {"bool": "bool", "int": "int", "ptr": "void*", "float": "float",
                        "unused": "void"}[kind]
        if seen:
            ret, n = seen.most_common(1)[0]
            if n * 3 >= sum(seen.values()) * 2:
                return ret
        return None

    @staticmethod
    def _params_seen(protos: list[tuple[str, list[str]]]) -> list[collections.Counter]:
        seen: list[collections.Counter] = []
        for _, params in protos:
            for i, p in enumerate(params):
                while len(seen) <= i:
                    seen.append(collections.Counter())
                seen[i][p] += 1
        return seen

    @staticmethod
    def _params_from(seen: list[collections.Counter], words: int) -> list[str] | None:
        if words == 0:
            return []
        params: list[str] = []
        used = 0
        for counter in seen:
            if used >= words:
                break
            kind = counter.most_common(1)[0][0]
            params.append(kind)
            used += 2 if kind in ("double", "int64") else 1
        if used != words:
            return None if used > words else params + ["int"] * (words - used)
        return params

    @staticmethod
    def _prototype(fn: kl.Function) -> tuple[str, list[str]] | None:
        head = ""
        for line in fn.code.splitlines():
            stripped = line.strip()
            if not stripped or stripped.startswith(("/*", "//", "*")):
                continue
            head += " " + stripped
            if ")" in stripped:
                break
        m = PROTO_RE.match(head.strip())
        if not m:
            return None
        ret_text = m.group("ret").strip() or "void"
        params = [p.strip() for p in m.group("params").split(",") if p.strip()]
        if params and re.search(r"\bthis\b", params[0]):
            params = params[1:]
        if params == ["void"]:
            params = []
        return _c_kind(ret_text, ret=True), [_c_kind(re.sub(r"\s*\w+$", "", p) or p) for p in params]

    def _call_site_usage(self) -> dict[int, collections.Counter]:
        usage: dict[int, collections.Counter] = collections.defaultdict(collections.Counter)
        if self.ledger.listing is None:
            return usage
        wanted: dict[str, set[int]] = collections.defaultdict(set)
        for caller, slot, cls, recv in self.ledger.db.execute(
                "SELECT caller, slot, cls, recv FROM vcalls WHERE module = ?", (self.module,)):
            if slot not in self.ledger.slot_bodies:
                continue
            if cls in self.family or cls in self.troika_chain:
                wanted[caller].add(slot)
            elif cls == "" and recv == "*(int *)this":
                fn = self.ledger.functions.get(self.ledger.resolve(caller))
                if fn is not None and self.receiver(fn) == (self.receiver(fn)[0], False)                         and self.receiver(fn)[0] is not None:
                    wanted[caller].add(slot)
        starts = sorted(int(a, 16) for a in self.ledger.functions)
        import bisect
        by_func: dict[str, set[int]] = collections.defaultdict(set)
        for caller, slots in wanted.items():
            i = bisect.bisect_right(starts, int(caller, 16)) - 1
            if i >= 0:
                by_func[f"{starts[i]:08x}"] |= slots
        for func, slots in sorted(by_func.items()):
            row = self.ledger.listing.execute(
                "SELECT asm FROM listing WHERE module = ? AND addr = ?", (self.module, func)).fetchone()
            if not row:
                continue
            lines = row[0].splitlines()
            for i, line in enumerate(lines):
                m = CALL_SITE_RE.match(line)
                if not m:
                    continue
                off = int(m.group(1), 16)
                if off % 4 or off // 4 not in slots:
                    continue
                usage[off // 4][_use_after(lines[i + 1:i + 3])] += 1
        return usage


def _use_after(lines: list[str]) -> str:
    for line in lines:
        m = ASM_LINE_RE.match(line)
        if not m:
            continue
        mn, ops = m.group("mn"), m.group("ops")
        if mn == "ADD" and ops.startswith("ESP"):
            continue
        if mn in X87_USE:
            return "float"
        tokens = re.findall(r"\b[A-Z]{2,3}\b", ops)
        if mn in ("MOV", "MOVZX", "MOVSX", "LEA", "XOR", "POP", "SETZ", "SETNZ") and tokens and tokens[0] in ("EAX", "AL", "AX"):
            # the first operand is overwritten; a `MOV EAX,EAX` or `XOR EAX,EAX` is not a use
            if mn == "MOVZX" and "AL" in tokens[1:]:
                return "bool"
            return "unused"
        if "[EAX" in ops:
            return "ptr"
        if "AL" in tokens and "EAX" not in tokens:
            return "bool"
        if "EAX" in tokens:
            return "int"
        return "unused"
    return "unused"


def _c_kind(text: str, ret: bool = False) -> str:
    t = re.sub(r"\bunsigned\s+", "u", text.strip())
    if t.endswith("*"):
        return "void*"
    if t in ("float", "float10") and ret:
        return "float"
    if t == "float":
        return "float"
    if t in ("double",):
        return "double"
    if t in ("bool",):
        return "bool"
    if t in ("undefined1", "byte", "char", "uchar"):
        return "bool" if ret else "char"
    if t in ("undefined2", "short", "ushort"):
        return "short"
    if t in ("undefined8", "longlong", "ulonglong"):
        return "int64"
    if t == "void":
        return "void"
    return "int"


