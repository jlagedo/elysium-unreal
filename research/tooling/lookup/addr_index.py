FORMAT_VERSION = 1
DEFAULT_ROWS = 8

REPO = Path(__file__).resolve().parents[3]

# What is indexed, as (directory under the repo, extensions, kind). The kind decides how a hit is
# shown: `ledger` rows are table rows, `doc` hits are prose under a heading, `port` hits are
# source, and `spec` hits are only counted. A port file a generator wrote is `generated`: it names
# every slot body by address and is the ledger's own reflection, not a citation of it.
ROOTS = (
    ("docs/vtmb", (".md", ".tsv"), "doc"),
    ("docs/contracts", (".md",), "doc"),
    ("docs/specs", (".md", ".tsv"), "spec"),
    ("research/tooling/ghidra/driver", (".tsv",), "ledger"),
    ("Source/ElysiumUE/Private", (".h", ".cpp", ".inl"), "port"),
    ("Source/ElysiumUE/Public", (".h", ".cpp", ".inl"), "port"),
    ("Source/ElysiumUEAnimGraph", (".h", ".cpp", ".inl"), "port"),
)
LEDGER_DIR = "docs/vtmb/npc-kernel/"
SKIP_DIRS = {"__pycache__", "ThirdParty", "Intermediate", "Binaries", ".git", "node_modules"}
GENERATED = b"// generated by"                # the first line of a file a generator wrote (lowered)

FUNCTIONS_MD = LEDGER_DIR + "functions.md"
SLOTS_MD = LEDGER_DIR + "slots.md"
LAYOUT_TSV = LEDGER_DIR + "layout.tsv"
NAMES_TSV = "research/tooling/ghidra/driver/names.tsv"
VERDICTS_TSV = "research/tooling/ghidra/driver/kernel_verdicts.tsv"
NAME_TABLES = (FUNCTIONS_MD, SLOTS_MD, LAYOUT_TSV, NAMES_TSV)

# How a query is read. An address is `0x` and 6-8 hex digits, or a bare eight (a table cell, a
# `FUN_` name); a bare run of fewer is not taken, because six hex digits is also a word.
ADDRESS = re.compile(r"^(?:0x)?([0-9a-fA-F]{8})$|^0x([0-9a-fA-F]{6,7})$"
                     r"|^(?:thunk_)?(?:FUN|LAB|DAT)_([0-9a-fA-F]{8})$")
SLOT = re.compile(r"^(?:slots?\s*#?\s*|#|vfunc)(\d{1,4})$|^(\d{1,3})$", re.IGNORECASE)
OFFSET = re.compile(r"^(?:\+0x|0x)([0-9a-fA-F]{1,5})$")
IDENTIFIER = re.compile(r"^~?[A-Za-z_][A-Za-z0-9_]*(?:::~?[A-Za-z_][A-Za-z0-9_]*)*$")

# What the text says. Matched against the lower-cased blob, so lower-case classes only.
CITATION = re.compile(rb"(?<![0-9a-z])(?:0x)?([1-3][0-9a-f]{7})(?![0-9a-z])")
HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
FUNCTION_ROW = re.compile(r"^\| `0x([0-9a-f]{8})` \| ([^|]+?) \|")
SLOT_ROW = re.compile(r"^\| (\d+) \| `0x([0-9a-f]{8})` ([^|]+?) \|")
DEFINITION = re.compile(r"^[A-Za-z_][^;{}()=]*?\b([A-Za-z_]\w*(?:::~?\w+)+)\s*\(")
VERDICT_WORDS = ("rule", "mechanism", "present", "dead", "unsettled")

MAX_HITS = 50_000               # per needle; a name that common is counted, not listed
_ALNUM = frozenset(b"0123456789abcdefghijklmnopqrstuvwxyz")
_WORD = _ALNUM | {ord("_")}


def load_local_environment() -> None:
    """`.elysium.local.env`, read directly: run as a script, this has no CLI to load it."""
    if os.environ.get("ELYSIUM_WORK_ROOT"):
        return
    for parent in Path(__file__).resolve().parents:
        candidate = parent / ".elysium.local.env"
        if candidate.is_file():
            for line in candidate.read_text(encoding="utf-8-sig").splitlines():
                line = line.strip()
                if line and not line.startswith("#") and "=" in line:
                    name, _, value = line.partition("=")
                    os.environ.setdefault(name.strip(), value.strip().strip("'\""))
            return


def cache_dir(repo: Path) -> Path:
    from elysium_pipeline.paths import cache_root
    # One index per checkout: the files it describes are the checkout's own.
    key = hashlib.sha256(str(repo.resolve()).lower().encode()).hexdigest()[:10]
    return cache_root() / "where-index" / key


