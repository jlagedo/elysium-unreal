def _clip(text: str, width: int, near: str | None = None) -> str:
    """A line cut to `width` characters, around `near` when the line is longer."""
    text = " ".join(text.strip().split())
    if len(text) <= width:
        return text
    at = text.lower().find(near.lower()) if near else -1
    start = max(0, at - width // 3) if at > 0 else 0
    return ("… " if start else "") + text[start:start + width] + (
        " …" if start + width < len(text) else "")


def _cells(rel: str, line: str) -> list[str]:
    if rel.endswith(".tsv"):
        return [cell.strip() for cell in line.split("\t")]
    return [cell.strip().replace("`", "") for cell in line.strip().strip("|").split("|")]


def _row(index: Index, rel: str, number: int, needle: str) -> str:
    """A ledger row: its first cells, and its verdict if it is a checklist row."""
    cells = _cells(rel, index.line(rel, number))
    shown = _clip(" | ".join(cells[:6]), 150, needle)
    verdict = next((cell for cell in cells if cell in VERDICT_WORDS), None)
    return shown + (f"  [verdict {verdict}]" if verdict and verdict not in shown else "")


def _is_row(index: Index, rel: str, number: int, needles: list[str]) -> bool:
    """Whether a line is a table row OF the needle (its first cells) rather than a mention in it."""
    line = index.line(rel, number)
    if rel.endswith(".tsv"):
        head = line.split("\t")[:5]             # `layout.tsv` keys its row by the 4th column
    elif line.startswith("|"):
        head = line.split("|")[1:3]
    else:
        return False
    text = " ".join(head).lower()
    return any(needle in text for needle in needles)


def _symbol(index: Index, rel: str, number: int) -> str:
    """The function a source line sits in: the nearest definition above it, at column 0."""
    for back in range(number - 1, max(0, number - 800), -1):
        line = index.line(rel, back)
        if line[:1].isalpha() or line[:1] == "_":
            match = DEFINITION.match(line)
            if match:
                return match.group(1)
    return ""


def _group(hits: dict[int, set[int]], index: Index, kinds: tuple[str, ...]) -> dict[int, list[int]]:
    return {fid: sorted(lines) for fid, lines in hits.items() if index.files[fid][1] in kinds}


def _more(counter: Counter) -> str:
    """`a.md x5; b.md x3 ...`: what was not listed, by file."""
    ranked = counter.most_common()
    return "; ".join(f"{Path(name).name} x{n}" for name, n in ranked[:6]) + (
        f"; and {len(ranked) - 6} more file(s)" if len(ranked) > 6 else "")


LEDGER_ORDER = ("functions.md", "slots.md", "fields.md", "entries.md", "checklist", "signatures.md",
                "layout.md", "layout.tsv", "order.md", "coverage.md", "kernel_verdicts.tsv")


def _ledger_rank(rel: str) -> tuple[int, str]:
    name = Path(rel).name
    for rank, prefix in enumerate(LEDGER_ORDER):
        if name.startswith(prefix):
            return rank, rel
    return len(LEDGER_ORDER), rel


def _doc_rank(rel: str) -> tuple[int, str]:
    if rel.startswith("docs/vtmb/npc-ai/"):
        return 0, rel
    if rel.startswith("docs/vtmb/"):
        return 1, rel
    return 2, rel


def _short(rel: str) -> str:
    for prefix in ("docs/vtmb/", "Source/ElysiumUE/"):
        if rel.startswith(prefix):
            return rel[len(prefix):]
    return rel


def _ledger_lines(index: Index, hits: dict[int, list[int]], literals: list[str],
                  rows: int) -> list[str]:
    """The ledger: the rows OF the query, a table at a time, then where it is only mentioned."""
    rowed: dict[str, list[int]] = defaultdict(list)
    mentions: Counter = Counter()
    for fid, lines in hits.items():
        rel = index.files[fid][0]
        for number in lines:
            if _is_row(index, rel, number, literals):
                rowed[rel].append(number)
            else:
                mentions[rel] += 1
    out = [f"   ledger (npc-kernel tables and overlays): {sum(map(len, rowed.values()))} row(s) in "
           f"{len(rowed)} table(s), {sum(mentions.values())} mention(s)"]
    left: Counter = Counter()
    shown = 0
    for rel in sorted(rowed, key=_ledger_rank):
        # Two rows of a table say what it says; a table of call edges has hundreds.
        take = max(0, min(2, rows - shown))
        for number in rowed[rel][:take]:
            out.append(f"     {Path(rel).name}:{number}  {_row(index, rel, number, literals[0])}")
            shown += 1
        if len(rowed[rel]) > take:
            left[rel] = len(rowed[rel]) - take
    if left:
        out.append("     more rows in: " + _more(left))
    if mentions:
        out.append("     mentioned in: " + _more(mentions))
    return out


def _doc_lines(index: Index, hits: dict[int, list[int]], literals: list[str], rows: int) -> list[str]:
    """The prose: the sections whose heading holds it first, then the sections that mention it."""
    named, mentioned = [], []
    for fid, lines in hits.items():
        rel = index.files[fid][0]
        heads = {line for line, _, _ in index.heads.get(fid, [])}
        for number in lines:
            (named if number in heads else mentioned).append((_doc_rank(rel), number, fid))
    named.sort()
    mentioned.sort()
    out = [f"   docs (docs/vtmb, docs/contracts): {len(named) + len(mentioned)} line(s) in "
           f"{len(hits)} file(s)"]
    shown, per_file = [], Counter()
    for entry in named + mentioned:
        if len(shown) >= rows:
            break
        if per_file[entry[2]] < (3 if entry in named else 2):
            shown.append(entry)
            per_file[entry[2]] += 1
    for _, number, fid in shown:
        rel = index.files[fid][0]
        head = index.heading_at(fid, number)
        if head and head[0] == number:
            out.append(f"     {_short(rel)}:{number}  [heading] {_clip(head[2], 120, literals[0])}")
        else:
            label = f"  § {_clip(head[2], 60)}" if head else ""
            out.append(f"     {_short(rel)}:{number}{label}  -- "
                       f"{_clip(index.line(rel, number), 110, literals[0])}")
    rest = Counter(index.files[fid][0] for entry in named + mentioned if entry not in shown
                   for fid in (entry[2],))
    if rest:
        out.append(f"     ... {sum(rest.values())} more line(s): " + _more(rest))
    return out


def _port_lines(index: Index, hits: dict[int, list[int]], made: dict[int, list[int]],
                literals: list[str], rows: int) -> list[str]:
    """The port: where the runtime already cites it -- its source before its tests, because a test
    that cites an address is evidence of coverage, not of the port body."""
    listed = sorted(((index.files[fid][0], lines) for fid, lines in hits.items()),
                    key=lambda one: ("/Tests/" in one[0], one[0]))
    out = [f"   port (Source/): {sum(len(lines) for _, lines in listed)} line(s) in "
           f"{len(listed)} file(s)"
           + (f"; plus {sum(map(len, made.values()))} in {len(made)} generated table(s), "
              f"which are not citations" if made else "")]
    shown = 0
    rest: Counter = Counter()
    for rel, lines in listed:
        take = max(0, min(2, rows - shown))
        for number in lines[:take]:
            symbol = _symbol(index, rel, number)
            out.append(f"     {_short(rel)}:{number}" + (f"  in {symbol}" if symbol else "")
                       + f"  -- {_clip(index.line(rel, number), 100, literals[0])}")
            shown += 1
        if len(lines) > take:
            rest[rel] = len(lines) - take
    if rest:
        out.append(f"     ... {sum(rest.values())} more line(s): " + _more(rest))
    return out


def render(index: Index, wanted: Plan, rows: int = DEFAULT_ROWS) -> str:
    """One query's answer."""
    out = [f"== {wanted.text}"]
    out += [f"   {line}" for line in wanted.heading]
    out += [f"   note: {line}" for line in wanted.notes]
    if not wanted.needles:
        out.append("   nothing to search for: a query is an address, a name, a field, an offset, "
                   "`slot N`, or text of three characters or more")
        return "\n".join(out)

    hits: dict[int, set[int]] = defaultdict(set)
    cut = False
    for needle, how in wanted.needles:
        found, _, over = index.find(needle, how)
        for fid, lines in found.items():
            hits[fid].update(lines)
        cut = cut or over
    for rel, line in wanted.pinned:
        if rel in index.file_ids:
            hits[index.file_ids[rel]].add(line)
    if not hits:
        out.append("   no mention in docs/vtmb, the ledger, the port or the specs")
        return "\n".join(out)
    literals = [needle.lower() for needle, _ in wanted.needles]

    ledger = _group(hits, index, ("ledger",))
    if ledger:
        out += _ledger_lines(index, ledger, literals, rows)
    docs = _group(hits, index, ("doc",))
    if docs:
        out += _doc_lines(index, docs, literals, rows)
    port, made = _group(hits, index, ("port",)), _group(hits, index, ("generated",))
    if port or made:
        out += _port_lines(index, port, made, literals, rows)
    # The specs only say how many: they are the stories' own text.
    specs = _group(hits, index, ("spec",))
    if specs:
        by_story: Counter = Counter()
        for fid, lines in specs.items():
            by_story["/".join(index.files[fid][0].split("/")[2:3]) or "docs/specs"] += len(lines)
        out.append(f"   specs (docs/specs): {sum(map(len, specs.values()))} line(s) in "
                   f"{len(specs)} file(s): "
                   + ", ".join(f"{name} x{n}" for name, n in by_story.most_common(6)))
    if cut:
        out.append(f"   (counted to {MAX_HITS:,} hits for a search term and stopped: it is too "
                   f"common to list; ask for a longer name)")
    return "\n".join(out)


def where(queries: str | list[str], rows: int = DEFAULT_ROWS) -> str:
    """The `where` answer for one query or several, each in its own block."""
    index = ensure_index()
    texts = [queries] if isinstance(queries, str) else list(queries)
    if not texts or not any(one.strip() for one in texts):
        return "where needs an address, a name, a field or `slot N`"
    return "\n\n".join(render(index, plan(index, one), rows) for one in texts if one.strip())


