# -*- coding: utf-8 -*-
"""The address index: from a retail address, name, field or slot to everywhere the project already
speaks about it.

Answering "what do we know about `0x1028a380`" used to be a `grep` over `docs/vtmb` (1.4 MB
`functions.md`, 0.7-0.9 MB checklists), a second over the ledger, a third over `Source/`, and a read
of whatever those turned up: 800 shell searches and some 160 one-off scripts in twelve days, each
one to three seconds of which almost none was the search. This answers it in one call:

    uv run elysium research where 0x1028a380 CAI_BaseNPC::SelectSchedule m_scriptState
    uv run elysium research where "slot 442"

and, through the corpus server, as the `vtmb_where` tool. A query gets its `docs/vtmb` sections
(file, heading, line), its rows in the `npc-kernel` ledger tables, the port source lines that cite
it, and a count of the specs that mention it. (`--verbose` is a root option: without it the CLI
withholds a tool's output; `uv run python research/tooling/lookup/where.py ...` needs neither.)

The standing verbs over the same index -- `section`, `verdict`, `cited`, `rows` -- are the questions
the one-off scripts kept asking; each is `research/tooling/lookup/<verb>.py`.

How it is built. Every input is a text file the project already owns: `docs/vtmb`, `docs/contracts`,
`docs/specs`, the ledger's `.tsv` overlays beside the corpus driver, and the port's `.h`, `.cpp` and
`.inl` under `Source/`. They are packed into one lower-cased blob with a table of line starts, so a
query is a `find` through memory-mapped bytes -- any literal, with no tokeniser to disagree about
what a name is -- and a position becomes (file, line) by bisection. What a blob cannot say is parsed
once at build: headings (the section a line sits in), the name tables the ledger holds
(`functions.md`, `names.tsv`, `layout.tsv`, `slots.md`), which let a name find its address and an
address its name, and the port's citations of every address, so asking which of 2,500 addresses the
port never cites is one pass and not 2,500 searches. The whole is keyed on the input hash (every
input's path, size and mtime, and the format version) under
`$ELYSIUM_WORK_ROOT/cache/where-index/<checkout>/`: a cold rebuild is seconds, an unchanged tree
rebuilds nothing.

A line is shown from the file on disk, not from the blob, so what is printed is the file as it is;
and a file that changed since the build changed the input hash, so the index was rebuilt before it
was asked.
"""

