# Loading and searching.

class Index:
    """A loaded index. `text` is the memory-mapped blob; everything else is small."""

    def __init__(self, repo: Path, directory: Path, key: str) -> None:
        with (directory / f"index-{key}.pkl").open("rb") as handle:
            tables = pickle.load(handle)
        self.repo = repo
        self.directory = directory
        self.key = key
        self.files: list[tuple[str, str]] = tables["files"]
        self.first_line: list[int] = tables["first_line"]
        self.nlines: list[int] = tables["nlines"]
        self.line_starts = array("I")
        self.line_starts.frombytes(tables["line_starts"])
        self.heads: dict[int, list[tuple[int, int, str]]] = tables["heads"]
        self.addr_names: dict[str, list[str]] = tables["addr_names"]
        self.name_addrs: dict[str, list[str]] = tables["name_addrs"]
        self.member_addrs: dict[str, list[tuple[str, str]]] = tables["member_addrs"]
        self.fields: dict[str, list[tuple[str, int, str]]] = tables["fields"]
        self.offsets: dict[int, list[tuple[str, str, str]]] = tables["offsets"]
        self.slots: dict[int, tuple[int, str, str]] = tables["slots"]
        self.port_cites: dict[str, list[tuple[int, int]]] = tables["port_cites"]
        self._file = (directory / f"text-{key}.bin").open("rb")
        self.text = mmap.mmap(self._file.fileno(), 0, access=mmap.ACCESS_READ)
        self.file_ids = {rel: number for number, (rel, _) in enumerate(self.files)}
        self._lines: dict[str, list[str]] = {}

    def close(self) -> None:
        self.text.close()
        self._file.close()

    def locate(self, position: int) -> tuple[int, int]:
        """(file id, 1-based line) of a byte offset in the blob."""
        line = bisect.bisect_right(self.line_starts, position) - 1
        file_id = bisect.bisect_right(self.first_line, line) - 1
        return file_id, line - self.first_line[file_id] + 1

    def line(self, rel: str, number: int) -> str:
        """One line as the file on disk has it."""
        if rel not in self._lines:
            try:
                # Bytes, not `read_text`: universal newlines would turn a lone `\r` into a line
                # break the blob's line table does not have, and every number after it would be off.
                text = (self.repo / rel).read_bytes().decode("utf-8", "replace")
            except OSError:
                text = ""
            self._lines[rel] = text.split("\n")
        lines = self._lines[rel]
        return lines[number - 1].rstrip("\r") if 0 < number <= len(lines) else ""

    def heading_at(self, file_id: int, line: int) -> tuple[int, int, str] | None:
        """The nearest heading at or above a line."""
        heads = self.heads.get(file_id)
        if not heads:
            return None
        index = bisect.bisect_right(heads, (line, 99, "\U0010ffff")) - 1
        return heads[index] if index >= 0 else None

    def section_end(self, file_id: int, head: tuple[int, int, str]) -> int:
        """The last line of a heading's section: the line before the next heading of its level or
        higher, or the end of the file."""
        heads = self.heads[file_id]
        position = bisect.bisect_left(heads, head)
        for line, level, _ in heads[position + 1:]:
            if level <= head[1]:
                return line - 1
        return self.nlines[file_id]

    def _bounded(self, start: int, end: int, how: str) -> bool:
        if how == "raw":
            return True
        before = self.text[start - 1] if start else 0
        after = self.text[end] if end < len(self.text) else 0
        if how == "tail":                       # `+0x5b7c`: what follows must not extend the number
            return after not in _ALNUM
        if how == "address":                    # a longer hex run is a different number
            if before == ord("x") and start >= 2 and self.text[start - 2] == ord("0"):
                before = 0                      # the `0x` of `0x1028a380` is part of the address
            return before not in _ALNUM and after not in _ALNUM
        if how == "slot":                       # a number that something calls a slot
            if after in _ALNUM:
                return False
            window = self.text[max(0, start - 8):start].decode("latin-1")
            return re.search(r"(?:slots?\s*#?\s*|#|vfunc)$", window) is not None
        return before not in _WORD and after not in _WORD       # "word": not inside a longer name

    def find(self, needle: str, how: str = "word") -> tuple[dict[int, list[int]], int, bool]:
        """Every line holding `needle`: ({file id: [lines]}, how many, whether it was cut short).

        `how` bounds the needle: "word" -- not inside a longer identifier; "address" -- not inside
        a longer run of letters and digits; "tail" -- not followed by one; "slot" -- a number
        something calls a slot (`slot 442`, `#442`, `vfunc442`); "raw" -- anywhere.
        """
        target = needle.lower().encode("utf-8")
        found: dict[int, set[int]] = defaultdict(set)
        count = 0
        position = self.text.find(target)
        while position != -1:
            if self._bounded(position, position + len(target), how):
                file_id, line = self.locate(position)
                found[file_id].add(line)
                count += 1
                if count >= MAX_HITS:
                    return {k: sorted(v) for k, v in found.items()}, count, True
            position = self.text.find(target, position + 1)
        return {k: sorted(v) for k, v in found.items()}, count, False


_CURRENT: Index | None = None


def ensure_index(repo: Path | None = None, directory: Path | None = None,
                 rebuild: bool = False) -> Index:
    """The index for this tree, built first if the input hash says it is not current."""
    global _CURRENT
    repo = repo or REPO                 # read at call time, so a test can point REPO elsewhere
    directory = directory or cache_dir(repo)
    inputs = discover(repo)
    key = fingerprint(inputs)
    if (_CURRENT is not None and _CURRENT.key == key and _CURRENT.repo == repo
            and _CURRENT.directory == directory and not rebuild):
        return _CURRENT
    ready = (directory / f"index-{key}.pkl").is_file() and (directory / f"text-{key}.bin").is_file()
    if rebuild or not ready:
        _write(directory, key, build(repo, inputs))
    if _CURRENT is not None:
        _CURRENT.close()
        _CURRENT = None
    try:
        _CURRENT = Index(repo, directory, key)
    except (OSError, ValueError, KeyError, EOFError, pickle.UnpicklingError):
        # A half-written or foreign file under the right name: build it again, once.
        _write(directory, key, build(repo, inputs))
        _CURRENT = Index(repo, directory, key)
    return _CURRENT


# ---------------------------------------------------------------------------
# Reading a query.

class Plan:
    """What a query asks: what to search for, and what the index already knows about it."""

    def __init__(self, text: str) -> None:
        self.text = text
        self.what = "text"                              # address | slot | offset | name | text
        self.needles: list[tuple[str, str]] = []      # (literal, how it must be bounded)
        self.heading: list[str] = []                  # what the tables say, before any hit
        self.notes: list[str] = []
        self.addresses: list[str] = []                # bare 8-hex addresses this query stands for
        self.pinned: list[tuple[str, int]] = []       # (file, line) the tables name outright


def plan(index: Index, text: str) -> Plan:
    """Classify a query and attach what the name tables know about it."""
    query = text.strip().strip("`'\"")
    result = Plan(query)
    address = ADDRESS.match(query)
    slot = SLOT.match(query)
    offset = OFFSET.match(query)
    if address:
        digits = next(group for group in address.groups() if group)
        value = digits.lower().rjust(8, "0")
        result.what = "address"
        result.addresses = [value]
        result.needles.append((value, "address"))
        names = index.addr_names.get(value, [])
        result.heading.append(f"0x{value}  " + (", ".join(names[:3]) if names
                                                  else "no name in the ledger or the overlay"))
    elif slot:
        number = int(slot.group(1) or slot.group(2))
        result.what = "slot"
        result.needles.append((str(number), "slot"))
        row = index.slots.get(number)
        result.heading.append(f"vtable slot {number}  " + (f"base body 0x{row[1]} {row[2]}"
                                                           if row else "not in the slots ledger"))
        if row:                       # the slots table keys its row by the bare number
            result.pinned.append((SLOTS_MD, row[0]))
    elif offset:
        value = int(offset.group(1), 16)
        result.what = "offset"
        for form in dict.fromkeys((f"+0x{value:x}", f"+0x{value:04x}")):
            result.needles.append((form, "tail"))
        for table, member, kind in index.offsets.get(value, [])[:6]:
            result.heading.append(f"+0x{value:04x}  {table}::{member}  ({kind})")
        if not index.offsets.get(value):
            result.heading.append(f"+0x{value:04x}  no field in layout.tsv")
    elif IDENTIFIER.match(query):
        result.what = "name"
        result.needles.append((query, "word"))
        key = query.lower()
        qualified = "::" in query
        candidates = (index.name_addrs.get(key, []) if qualified else
                      [addr for _, addr in index.member_addrs.get(key, [])])
        candidates = list(dict.fromkeys(candidates))
        if candidates and len(candidates) <= 4:
            result.addresses = candidates
            for addr in candidates:
                result.needles.append((addr, "address"))
                result.heading.append(f"0x{addr}  " + ", ".join(index.addr_names.get(addr, [])[:3]))
        elif candidates:
            named = [f"0x{addr} {index.addr_names.get(addr, ['?'])[0]}" for addr in candidates[:6]]
            result.notes.append(f"{len(candidates)} functions are named {query}: "
                                + "; ".join(named) + (" ..." if len(candidates) > 6 else "")
                                + " -- pass an address or Class::Method to scope it")
        for table, off, kind in index.fields.get(key, [])[:6]:
            result.heading.append(f"{table}::{query}  +0x{off:04x}  ({kind})")
        if not qualified and len(index.fields.get(key, [])) > 6:
            result.notes.append(f"{len(index.fields[key])} layout rows name {query}")
    elif len(query) >= 3:
        result.needles.append((query, "raw"))
    return result


