# Building.

# An input: (path relative to the repo, kind, size, mtime in ns).
Input = tuple[str, str, int, int]


def discover(repo: Path) -> list[Input]:
    """Every input, in a fixed order, with the size and mtime the directory scan already holds.

    `os.walk` then `stat` is two system calls per file and ~0.1 ms each on Windows -- 0.2 s to
    learn that nothing changed. `DirEntry.stat()` answers from the scan itself, so the whole
    sweep, which every query makes, is a few milliseconds.
    """
    found: list[Input] = []
    root = str(repo)
    for sub, extensions, kind in ROOTS:
        if not (repo / sub).is_dir():
            continue
        batch: list[Input] = []
        stack = [os.path.join(root, *sub.split("/"))]
        while stack:
            directory = stack.pop()
            try:
                entries = list(os.scandir(directory))
            except OSError:
                continue
            for entry in entries:
                if entry.is_dir(follow_symlinks=False):
                    if entry.name not in SKIP_DIRS:
                        stack.append(entry.path)
                elif entry.name.endswith(extensions):
                    stat = entry.stat()
                    # Plain string work: `pathlib` costs more per file than the stat it is for.
                    rel = entry.path[len(root) + 1:].replace("\\", "/")
                    batch.append((rel, "ledger" if rel.startswith(LEDGER_DIR) else kind,
                                  stat.st_size, stat.st_mtime_ns))
        found += sorted(batch)
    return found


def fingerprint(inputs: list[Input]) -> str:
    """The input hash: the format version and every input's path, size and mtime.

    Stat, not content: reading 1,700 files to learn that nothing changed would cost a hundred
    times the stat, and a file whose bytes changed with its size and mtime unchanged is not a thing
    a checkout does. A checkout that rewrites every mtime (a `git checkout`) costs one rebuild.
    """
    digest = hashlib.sha256(f"{FORMAT_VERSION}\n".encode())
    for rel, kind, size, mtime in inputs:
        digest.update(f"{rel}\t{kind}\t{size}\t{mtime}\n".encode())
    return digest.hexdigest()[:16]


class Built:
    """What a build produces before it is written: the blob and the tables beside it."""

    def __init__(self) -> None:
        self.files: list[tuple[str, str]] = []
        self.first_line: list[int] = []
        self.nlines: list[int] = []
        self.blob = bytearray()
        self.line_starts = array("I")
        self.heads: dict[int, list[tuple[int, int, str]]] = {}
        self.addr_names: dict[str, list[str]] = defaultdict(list)
        self.name_addrs: dict[str, list[str]] = defaultdict(list)
        self.member_addrs: dict[str, list[tuple[str, str]]] = defaultdict(list)
        self.fields: dict[str, list[tuple[str, int, str]]] = defaultdict(list)
        self.offsets: dict[int, list[tuple[str, str, str]]] = defaultdict(list)
        self.slots: dict[int, tuple[int, str, str]] = {}
        self.port_cites: dict[str, list[tuple[int, int]]] = defaultdict(list)


def _name(built: Built, addr: str, name: str) -> None:
    name = name.strip().strip("`")
    if not name or name in built.addr_names[addr]:
        return
    built.addr_names[addr].append(name)
    built.name_addrs[name.lower()].append(addr)
    built.member_addrs[name.rsplit("::", 1)[-1].lower()].append((name, addr))


def _headings(lines: list[str]) -> list[tuple[int, int, str]]:
    """(line, level, text) of each heading outside a fenced block."""
    found = []
    fenced = False
    for number, line in enumerate(lines, 1):
        if line.startswith("```"):
            fenced = not fenced
        elif not fenced and line.startswith("#"):
            match = HEADING.match(line)
            if match:
                found.append((number, len(match.group(1)), match.group(2)[:200]))
    return found


def _tables(built: Built, rel: str, lines: list[str]) -> None:
    """The name tables the ledger holds, parsed from the files that carry them."""
    if rel == FUNCTIONS_MD:
        for line in lines:
            match = FUNCTION_ROW.match(line)
            if match:
                _name(built, match.group(1), match.group(2))
    elif rel == SLOTS_MD:
        for number, line in enumerate(lines, 1):
            match = SLOT_ROW.match(line)
            if match:
                built.slots.setdefault(int(match.group(1)),
                                       (number, match.group(2), match.group(3).strip()))
                _name(built, match.group(2), match.group(3))
    elif rel == NAMES_TSV:
        for line in lines:
            parts = line.split("\t")
            if len(parts) >= 3 and not line.startswith("#") and re.fullmatch(r"[0-9a-f]{8}",
                                                                              parts[1]):
                _name(built, parts[1], parts[2])
    elif rel == LAYOUT_TSV:
        header: list[str] | None = None
        for line in lines:
            if not line.strip() or line.startswith("#"):
                continue
            parts = line.split("\t")
            if header is None:
                header = parts
                continue
            row = dict(zip(header, parts))
            try:
                offset = int(row.get("offset", ""), 16)
            except ValueError:
                continue
            member = row.get("member", "")
            if member:
                entry = (row.get("table", ""), offset, row.get("type", ""))
                built.fields[member.lower()].append(entry)
                built.offsets[offset].append((entry[0], member, entry[2]))


def build(repo: Path, inputs: list[Input]) -> Built:
    """Read every input once."""
    built = Built()
    offset = 0
    for rel, kind, _, _ in inputs:
        data = (repo / rel).read_bytes()
        if not data.endswith(b"\n"):
            data += b"\n"
        file_id = len(built.files)
        lowered = data.lower()
        if kind == "port" and lowered.startswith(GENERATED):
            kind = "generated"
        built.files.append((rel, kind))
        pieces = lowered.split(b"\n")
        starts = list(accumulate((len(piece) + 1 for piece in pieces[:-1]), initial=offset))
        built.first_line.append(len(built.line_starts))
        built.nlines.append(len(starts) - 1)
        built.line_starts.extend(starts[:-1])
        built.blob += lowered
        if kind in ("port", "generated"):
            # Every address the port speaks of, with the line it speaks on: `cited` asks it of a
            # whole table, which as one search per address would be a minute.
            for match in CITATION.finditer(lowered):
                line = bisect.bisect_right(starts, offset + match.start()) - 1
                built.port_cites[match.group(1).decode()].append((file_id, line + 1))
        offset = starts[-1]
        if kind in ("doc", "ledger", "spec") or rel in NAME_TABLES:
            # Split on `\n` alone, the way the blob's line table is, so a heading's number is its
            # line; a Windows checkout's `\r` is part of no cell.
            lines = [line.rstrip("\r") for line in data.decode("utf-8", "replace").split("\n")]
            if rel.endswith(".md"):
                built.heads[file_id] = _headings(lines)
            _tables(built, rel, lines)
    return built


def _write(directory: Path, key: str, built: Built) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    blob, meta = directory / f"text-{key}.bin", directory / f"index-{key}.pkl"
    pid = os.getpid()
    tables = {
        "version": FORMAT_VERSION, "key": key, "files": built.files,
        "first_line": built.first_line, "nlines": built.nlines,
        "line_starts": built.line_starts.tobytes(), "heads": built.heads,
        "addr_names": dict(built.addr_names), "name_addrs": dict(built.name_addrs),
        "member_addrs": dict(built.member_addrs), "fields": dict(built.fields),
        "offsets": dict(built.offsets), "slots": built.slots,
        "port_cites": dict(built.port_cites),
    }
    (directory / f"text-{key}.{pid}.tmp").write_bytes(bytes(built.blob))
    with (directory / f"index-{key}.{pid}.tmp").open("wb") as handle:
        pickle.dump(tables, handle, protocol=pickle.HIGHEST_PROTOCOL)
    # Data first, the pointer last. Two processes that build the same key write the same bytes, so
    # a replace that loses to a mapped copy of itself has nothing to say.
    for source, target in ((f"text-{key}.{pid}.tmp", blob), (f"index-{key}.{pid}.tmp", meta)):
        try:
            os.replace(directory / source, target)
        except PermissionError:
            (directory / source).unlink(missing_ok=True)
    for old in directory.iterdir():             # earlier builds; one still mapped stays put
        if old.name not in (blob.name, meta.name):
            try:
                old.unlink()
            except OSError:
                pass


