def _sections(index: Index, wanted: Plan) -> tuple[list[tuple[int, int]], bool]:
    """The sections that answer a query: [(file id, heading line)], and whether a heading names it.

    A heading that holds the needle is the best answer a doc can give -- the section is ABOUT it.
    When none does, the sections its mentions sit under are what there is.
    """
    hits: dict[int, set[int]] = defaultdict(set)
    for needle, how in wanted.needles:
        for fid, lines in index.find(needle, how)[0].items():
            hits[fid].update(lines)
    named: list[tuple[tuple[int, str], int, int]] = []
    inside: dict[tuple[int, int], tuple[int, str]] = {}
    for fid, lines in hits.items():
        rel, kind = index.files[fid]
        if not rel.endswith(".md") or kind not in ("doc", "ledger", "spec"):
            continue
        rank = (_doc_rank(rel)[0] if kind == "doc" else 3 if kind == "spec" else 4, rel)
        heads = {line for line, _, _ in index.heads.get(fid, [])}
        for number in lines:
            head = index.heading_at(fid, number)
            if head is None:
                continue
            if number in heads:
                # The deepest heading first: `### 0x1028a380 SelectSchedule` is about it; the
                # `## ... family Select19` that holds it is about the family.
                named.append(((rank[0], -head[1], rank[1]), fid, number))
            elif kind == "doc":
                inside.setdefault((fid, head[0]), rank)
    if named:
        return [(fid, line) for _, fid, line in sorted(set(named))], True
    return [key for key, _ in sorted(inside.items(), key=lambda item: (item[1], item[0]))], False


def section(text: str, lines: int = 60, pick: int = 1, start: int | None = None) -> str:
    """The section of the docs that is about `text`, without reading the file around it."""
    index = ensure_index()
    wanted = plan(index, text)
    if not wanted.needles:
        return f"section needs an address, a name, a field or `slot N`; got {text!r}"
    found, named = _sections(index, wanted)
    if not found:
        return f"no docs section mentions {text}; `where {text}` says where else it is spoken of"
    out = [f"== {text}: " + (f"{len(found)} section(s) whose heading names it" if named else
                             f"no heading names it; the {len(found)} section(s) its mentions sit in")]
    for number, (fid, line) in enumerate(found[:12], 1):
        rel = index.files[fid][0]
        head = next(one for one in index.heads[fid] if one[0] == line)
        out.append(f"   [{number}] {rel}:{line}  {_clip(head[2], 90)}  "
                   f"({index.section_end(fid, head) - line + 1} lines)")
    if len(found) > 12:
        out.append(f"   ... {len(found) - 12} more")
    if not 1 <= pick <= len(found):
        return "\n".join(out + [f"pick={pick} is outside 1-{len(found)}"])
    fid, line = found[pick - 1]
    rel = index.files[fid][0]
    head = next(one for one in index.heads[fid] if one[0] == line)
    last = index.section_end(fid, head)
    first = max(line, start or line)
    limit = min(last, first + max(1, lines) - 1)
    out.append(f"\n--- [{pick}] {rel}:{first}-{limit} of {line}-{last}")
    out += [index.line(rel, number) for number in range(first, limit + 1)]
    if limit < last:
        out.append(f"--- {last - limit} more line(s): `section {text} --pick {pick} "
                   f"--from {limit + 1}` continues, --lines sets the page")
    return "\n".join(out)


def _tsv(path: Path) -> tuple[list[str], list[list[str]]]:
    """A tab-separated table: its header, and its rows. Lines starting `#` are comments; cells are
    split on tabs and never unquoted, because the evidence column holds quotation marks."""
    header: list[str] | None = None
    rows: list[list[str]] = []
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        cells = line.split("\t")
        if header is None:
            header = cells
        else:
            rows.append(cells + [""] * (len(header) - len(cells)))
    return header or [], rows


def verdict(queries: list[str], band: str | None = None, which: str | None = None,
            target: str | None = None, count: bool = False, full: bool = False,
            rows: int = 40) -> str:
    """`kernel_verdicts.tsv`: the porting verdict of an address, or of a band, or the standing."""
    path = REPO / VERDICTS_TSV
    if not path.is_file():
        return f"no verdict overlay at {VERDICTS_TSV}"
    header, table = _tsv(path)
    column = {name: number for number, name in enumerate(header)}
    index = ensure_index()
    wanted: set[str] = set()
    for text in queries:
        planned = plan(index, text)
        if planned.addresses:
            wanted.update(planned.addresses)
        else:
            return f"verdict takes addresses or Class::Method names it can resolve; got {text!r}"
    selected = [row for row in table
                if (not wanted or row[column["address"]].lower() in wanted)
                and (band is None or row[column["band"]] == band)
                and (which is None or row[column["verdict"]] == which)
                and (target is None or target.lower() in row[column["target"]].lower())]
    out = []
    if count or not (wanted or band or which or target):
        grid: Counter = Counter((row[column["band"]], row[column["verdict"]]) for row in selected)
        bands = sorted({b for b, _ in grid}, key=lambda one: [int(n) for n in re.findall(r"\d+", one)])
        out.append(f"{len(selected)} verdict row(s) of {len(table)}")
        out.append("band\t" + "\t".join(VERDICT_WORDS) + "\ttotal")
        for one in bands:
            cells = [grid[(one, word)] for word in VERDICT_WORDS]
            out.append(f"{one}\t" + "\t".join(map(str, cells)) + f"\t{sum(cells)}")
        return "\n".join(out)
    for row in selected[:rows]:
        names = index.addr_names.get(row[column["address"]].lower(), [])
        evidence = row[column["evidence"]]
        out.append(f"0x{row[column['address']]}  {row[column['verdict']]:10} band {row[column['band']]:6}"
                   f" {names[0] if names else '?'}\n    target: {row[column['target']]}\n"
                   f"    evidence: {evidence if full else _clip(evidence, 220)}")
    if len(selected) > rows:
        out.append(f"... {len(selected) - rows} more of {len(selected)}; --limit shows more, "
                   f"--count tabulates")
    return "\n".join(out) or "no verdict row matches"


def cited(queries: list[str], table: str | None = None, column: str = "address",
          where_: list[str] | None = None, show_all: bool = False, rows: int = 40) -> str:
    """Which addresses the port cites, and where; or which of a table's addresses it never does."""
    index = ensure_index()
    port = {fid for fid, (_, kind) in enumerate(index.files) if kind == "port"}

    def citations(addr: str) -> list[tuple[int, int]]:
        return [(fid, line) for fid, line in index.port_cites.get(addr, []) if fid in port]

    addresses: list[tuple[str, str]] = []
    for text in queries:
        planned = plan(index, text)
        if not planned.addresses:
            return f"cited takes addresses or Class::Method names it can resolve; got {text!r}"
        addresses += [(addr, (index.addr_names.get(addr) or ["?"])[0]) for addr in planned.addresses]
    if table:
        path = resolve_table(table)
        header, body = _tsv(path)
        if column not in header:
            return f"{path.name} has no column {column!r}; its columns are {', '.join(header)}"
        keep = _filters(header, where_ or [])
        for cells in body:
            if all(test(cells) for test in keep):
                match = re.search(r"[0-9a-f]{8}", cells[header.index(column)].lower())
                if match:
                    addresses.append((match.group(0), (index.addr_names.get(match.group(0)) or ["?"])[0]))
    if not addresses:
        return "cited needs addresses, names, or --table"
    addresses = list(dict.fromkeys(addresses))
    out, uncited = [], 0
    for addr, name in addresses:
        found = citations(addr)
        uncited += not found
        if table and found and not show_all:
            continue
        if len(out) >= rows * 2:
            continue
        if found:
            by_file: dict[int, list[int]] = defaultdict(list)
            for fid, line in found:
                by_file[fid].append(line)
            spots = [f"{Path(index.files[fid][0]).name}:{','.join(map(str, sorted(set(lines))[:4]))}"
                     for fid, lines in sorted(by_file.items())[:4]]
            out.append(f"0x{addr}  {name}  cited {len(found)}x in {len(by_file)} file(s): "
                       + "; ".join(spots))
        else:
            out.append(f"0x{addr}  {name}  NOT CITED by the port")
    out.append(f"{len(addresses) - uncited} of {len(addresses)} address(es) cited by the port "
               f"(.h/.cpp/.inl under Source/, generated tables excluded)"
               + ("" if not table or show_all else "; only the uncited are listed, --all lists every one"))
    return "\n".join(out)


def resolve_table(name: str) -> Path:
    """A `.tsv` by path, or by file name under `docs/` and `research/tooling/`."""
    direct = Path(name)
    for candidate in (direct, REPO / name):
        if candidate.is_file():
            return candidate
    wanted = name.replace("\\", "/").lower()
    # A bare file name matches any directory's; a name with a directory in it only that one's.
    found = [path for sub in ("docs", "research/tooling") for path in (REPO / sub).rglob("*.tsv")
             if (path.as_posix().lower().endswith("/" + wanted) if "/" in wanted
                 else path.name.lower() == wanted)]
    if len(found) == 1:
        return found[0]
    if found:
        raise SystemExit(f"{name} is ambiguous: " + ", ".join(
            path.relative_to(REPO).as_posix() for path in sorted(found)))
    like = sorted({path.name for sub in ("docs", "research/tooling") for path in
                   (REPO / sub).rglob("*.tsv") if Path(name).stem.lower() in path.name.lower()})
    raise SystemExit(f"no table named {name}" + (f"; did you mean {', '.join(like[:8])}" if like else ""))


FILTER = re.compile(r"^(\w+)\s*(!=|!~|>=|<=|=|~|>|<)\s*(.*)$")


def _filters(header: list[str], clauses: list[str]):
    """`col=value`, `col!=value`, `col~substring`, `col!~substring`, `col>=number`... as tests."""
    tests = []
    for clause in clauses:
        match = FILTER.match(clause)
        if not match or match.group(1) not in header:
            raise SystemExit(f"{clause!r} is not a filter over {', '.join(header)}; write col=value, "
                             f"col!=value, col~text, col!~text or col>=number")
        number, operator, value = header.index(match.group(1)), match.group(2), match.group(3)

        def test(cells, number=number, operator=operator, value=value):
            cell = cells[number]
            if operator == "=":
                return cell.lower() == value.lower()
            if operator == "!=":
                return cell.lower() != value.lower()
            if operator == "~":
                return value.lower() in cell.lower()
            if operator == "!~":
                return value.lower() not in cell.lower()
            try:
                left, right = float(int(cell, 0) if cell.lower().startswith("0x") else cell), float(value)
            except ValueError:
                return False
            return {">": left > right, "<": left < right, ">=": left >= right,
                    "<=": left <= right}[operator]

        tests.append(test)
    return tests


def rows_of(table: str, clauses: list[str], columns: str | None = None, count_by: str | None = None,
            limit: int = 40, full: bool = False) -> str:
    """A tab-separated table, filtered, counted or projected -- the `csv.DictReader` and `Counter`
    a one-off script wrote each time."""
    path = resolve_table(table)
    header, body = _tsv(path)
    keep = _filters(header, clauses)
    selected = [cells for cells in body if all(test(cells) for test in keep)]
    name = path.relative_to(REPO).as_posix() if REPO in path.parents else str(path)
    if count_by:
        keys = [one.strip() for one in count_by.split(",")]
        missing = [one for one in keys if one not in header]
        if missing:
            raise SystemExit(f"{path.name} has no column {missing[0]!r}; its columns are "
                             f"{', '.join(header)}")
        grid = Counter(tuple(cells[header.index(one)] for one in keys) for cells in selected)
        out = [f"# {name}: {len(selected)} of {len(body)} rows, by {'/'.join(keys)}"]
        out += [f"{n}\t" + "\t".join(key) for key, n in grid.most_common(limit)]
        if len(grid) > limit:
            out.append(f"... {len(grid) - limit} more group(s); --limit shows more")
        return "\n".join(out)
    shown = [one.strip() for one in columns.split(",")] if columns else header
    missing = [one for one in shown if one not in header]
    if missing:
        raise SystemExit(f"{path.name} has no column {missing[0]!r}; its columns are "
                         f"{', '.join(header)}")
    picks = [header.index(one) for one in shown]
    out = [f"# {name}: {len(selected)} of {len(body)} rows", "\t".join(shown)]
    for cells in selected[:limit]:
        out.append("\t".join(cells[number] if full else _clip(cells[number], 80) for number in picks))
    if len(selected) > limit:
        out.append(f"... {len(selected) - limit} more row(s); --limit shows more, --count-by "
                   f"COLUMN counts them")
    return "\n".join(out)


# ---------------------------------------------------------------------------
# The command line, shared by the five `research` entry points beside this file.

def run(verb: str, argv: list[str]) -> int:
    load_local_environment()
    # The docs are UTF-8 and so is what is quoted from them; a console that is not must not turn
    # an em dash in a heading into a traceback.
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser(prog=verb, description=VERBS[verb][0])
    VERBS[verb][1](parser)
    arguments = parser.parse_args(argv)
    started = time.perf_counter()
    if verb == "where":
        if arguments.rebuild or arguments.stats:
            index = ensure_index(rebuild=arguments.rebuild)
            print(f"index {index.key}: {len(index.files)} files, {len(index.line_starts):,} lines, "
                  f"{len(index.text) // 1024:,} KB, {len(index.addr_names):,} named addresses, "
                  f"{len(index.port_cites):,} cited by the port; {time.perf_counter() - started:.2f} s")
            if not arguments.queries:
                return 0
        print(where(arguments.queries, arguments.limit))
    elif verb == "section":
        print(section(arguments.query, arguments.lines, arguments.pick, arguments.start))
    elif verb == "verdict":
        print(verdict(arguments.queries, arguments.band, arguments.verdict, arguments.target,
                      arguments.count, arguments.full, arguments.limit))
    elif verb == "cited":
        print(cited(arguments.queries, arguments.table, arguments.column, arguments.where,
                    arguments.all, arguments.limit))
    else:
        print(rows_of(arguments.table, arguments.filters, arguments.cols, arguments.count_by,
                      arguments.limit, arguments.full))
    return 0


def _where_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("queries", nargs="*", help="0x1028a380, CAI_BaseNPC::SelectSchedule, "
                        "m_scriptState, +0x5cc0, 'slot 442'")
    parser.add_argument("--limit", type=int, default=DEFAULT_ROWS, help="lines per section")
    parser.add_argument("--rebuild", action="store_true", help="rebuild the index first")
    parser.add_argument("--stats", action="store_true", help="say what the index holds")


def _section_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("query", help="an address, a name, a field")
    parser.add_argument("--lines", type=int, default=60, help="page length (default 60)")
    parser.add_argument("--pick", type=int, default=1, help="which listed section to print")
    parser.add_argument("--from", dest="start", type=int, default=None,
                        help="first line of the page, to continue one")


def _verdict_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("queries", nargs="*", help="addresses or names; none = the whole table")
    parser.add_argument("--band", default=None, help="a layer band, e.g. 5-9")
    parser.add_argument("--verdict", default=None, choices=VERDICT_WORDS)
    parser.add_argument("--target", default=None, help="the target contains this")
    parser.add_argument("--count", action="store_true", help="verdicts by band")
    parser.add_argument("--full", action="store_true", help="the evidence column whole")
    parser.add_argument("--limit", type=int, default=40)


def _cited_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("queries", nargs="*", help="addresses or names")
    parser.add_argument("--table", default=None, help="a .tsv whose addresses to check")
    parser.add_argument("--column", default="address", help="its address column")
    parser.add_argument("--where", action="append", default=None, metavar="COL=VALUE",
                        help="filter the table's rows (col=v, col!=v, col~text, col>=n)")
    parser.add_argument("--all", action="store_true", help="list the cited ones too")
    parser.add_argument("--limit", type=int, default=40)


def _rows_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("table", help="a .tsv, by path or file name (unported.tsv)")
    parser.add_argument("filters", nargs="*", help="col=value  col!=value  col~text  col!~text  "
                        "col>=number")
    parser.add_argument("--cols", default=None, help="the columns to show, comma-separated")
    parser.add_argument("--count-by", default=None, help="count the rows by these columns")
    parser.add_argument("--limit", type=int, default=40)
    parser.add_argument("--full", action="store_true", help="cells uncut")


VERBS = {
    "where": ("where the project already speaks about an address, name, field or slot",
              _where_arguments),
    "section": ("the docs section that is about an address or name", _section_arguments),
    "verdict": ("the porting verdict of an address, or of a band", _verdict_arguments),
    "cited": ("which addresses the port cites, or never does", _cited_arguments),
    "rows": ("filter, count or project a .tsv table", _rows_arguments),
}


if __name__ == "__main__":
    raise SystemExit(run(sys.argv[1], sys.argv[2:]))
